param([Parameter(Mandatory=$true)][string]$SourceRoot)
$ErrorActionPreference = 'Stop'
$configurePath = Join-Path $SourceRoot 'configure.ac'
$match = [regex]::Match([IO.File]::ReadAllText($configurePath), 'AC_INIT\(\[PHP\],\[(\d+)\.(\d+)\.(\d+)([^\]]*)\]')
if (-not $match.Success) { throw 'Cannot read PHP version from configure.ac.' }
$major = [int]$match.Groups[1].Value
$minor = [int]$match.Groups[2].Value
$release = [int]$match.Groups[3].Value
$extra = $match.Groups[4].Value
if ($extra -match '["\r\n\\]') { throw 'Unsupported version suffix.' }
$version = "$major.$minor.$release$extra"
$versionId = $major * 10000 + $minor * 100 + $release
$lines = @('/* automatically generated by configure */','/* edit configure.ac to change version number */',"#define PHP_MAJOR_VERSION $major","#define PHP_MINOR_VERSION $minor","#define PHP_RELEASE_VERSION $release",('#define PHP_EXTRA_VERSION "' + $extra + '"'),('#define PHP_VERSION "' + $version + '"'),"#define PHP_VERSION_ID $versionId")
$header = Join-Path $SourceRoot 'main\php_version.h'
$content = ($lines -join "`n") + "`n"
if ([IO.File]::ReadAllText($header).Replace("`r`n","`n") -ne $content) { [IO.File]::WriteAllText($header, $content, [Text.UTF8Encoding]::new($false)) }
Write-Output $version
